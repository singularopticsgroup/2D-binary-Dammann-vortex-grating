import numpy as np
import matplotlib.pyplot as plt

# SLM size
pX = 1024
pY = 768

# No of grooves in x direction and y direction
nx = 10
ny = 10

# Pixel size
p = 19e-6

x = np.arange(-pX // 2, pX // 2) * p
y = np.arange(-pY // 2, pY // 2) * p

X, Y = np.meshgrid(x, y)
Z = X + 1j * Y
r = np.sqrt(X**2 + Y**2)
phi = np.arctan2(Y, X)

# topological charge
l1 = 1
l2 = 5
l_p = -12

# transition points
t1 = 0.03863
t2 = 0.39084
t3 = 0.65552

# Spatial frequency in X-direction and Y-direction
fx = nx / (pX * p)
fy = ny / (pY * p)

# phase ramps in x and y
Gx = np.mod(2 * np.pi * fx * X + l1*phi, 2 * np.pi)
Gy = np.mod(2 * np.pi * fy * Y + l2*phi, 2 * np.pi)

# 0 to 1
ux = Gx / (2 * np.pi)
uy = Gy / (2 * np.pi)

# binary 1D masks
mx = np.zeros_like(ux, dtype=np.uint8)
my = np.zeros_like(uy, dtype=np.uint8)

mx[(ux >= t1) & (ux < t2)] = 1
mx[ux >= t3] = 1

my[(uy >= t1) & (uy < t2)] = 1
my[uy >= t3] = 1

# combine x and y masks
#mask = np.bitwise_xor(mx, my)
mask = (mx +my) % 2

# SLM image
slm = (mask * 255).astype(np.uint8)

# Phase vortex 12/-12
vortex_12 = np.mod(l_p*phi, 2 * np.pi)
vortex_gray = (255 * vortex_12 / (2 * np.pi)).astype(np.uint8)

plt.figure(figsize=(6, 6))
plt.imshow(vortex_gray, cmap='gray', vmin=0, vmax=255)
plt.axis('off')
plt.show()

plt.figure(figsize=(6, 6))
plt.imshow(slm, cmap='gray', vmin=0, vmax=255)
plt.axis('off')
plt.show()

from PIL import Image
# convert binary mask to actual phase: 0 or pi
phase_grating = mask * np.pi

# vortex phase
phase_vortex = np.mod(l_p * phi, 2 * np.pi)

# total phase = grating + vortex
phase_total = np.mod(phase_grating + phase_vortex, 2 * np.pi)

# map 0..2pi to 0..255 grayscale
slm_gray = (255 * phase_total / (2 * np.pi)).astype(np.uint8)

# display
plt.figure(figsize=(6, 6))
plt.imshow(slm_gray, cmap='gray', vmin=0, vmax=255)
plt.axis('off')
plt.show()

# save as BMP
Image.fromarray(slm_gray).save("grating_vortex_100_l_neg.bmp")
print("Saved as grating_vortex.bmp")